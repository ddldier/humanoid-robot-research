#!/usr/bin/env python3
from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np

POLICY_ORDER = ['left_hip_pitch_joint', 'right_hip_pitch_joint', 'waist_yaw_joint', 'left_hip_roll_joint', 'right_hip_roll_joint', 'waist_roll_joint', 'left_hip_yaw_joint', 'right_hip_yaw_joint', 'waist_pitch_joint', 'left_knee_joint', 'right_knee_joint', 'left_shoulder_pitch_joint', 'right_shoulder_pitch_joint', 'left_ankle_pitch_joint', 'right_ankle_pitch_joint', 'left_shoulder_roll_joint', 'right_shoulder_roll_joint', 'left_ankle_roll_joint', 'right_ankle_roll_joint', 'left_shoulder_yaw_joint', 'right_shoulder_yaw_joint', 'left_elbow_joint', 'right_elbow_joint', 'left_wrist_roll_joint', 'right_wrist_roll_joint', 'left_wrist_pitch_joint', 'right_wrist_pitch_joint', 'left_wrist_yaw_joint', 'right_wrist_yaw_joint']
CONVERTER_ORDER = ['left_hip_pitch_joint', 'left_hip_roll_joint', 'left_hip_yaw_joint', 'left_knee_joint', 'left_ankle_pitch_joint', 'left_ankle_roll_joint', 'right_hip_pitch_joint', 'right_hip_roll_joint', 'right_hip_yaw_joint', 'right_knee_joint', 'right_ankle_pitch_joint', 'right_ankle_roll_joint', 'waist_yaw_joint', 'waist_roll_joint', 'waist_pitch_joint', 'left_shoulder_pitch_joint', 'left_shoulder_roll_joint', 'left_shoulder_yaw_joint', 'left_elbow_joint', 'left_wrist_roll_joint', 'left_wrist_pitch_joint', 'left_wrist_yaw_joint', 'right_shoulder_pitch_joint', 'right_shoulder_roll_joint', 'right_shoulder_yaw_joint', 'right_elbow_joint', 'right_wrist_roll_joint', 'right_wrist_pitch_joint', 'right_wrist_yaw_joint']

parser = argparse.ArgumentParser(
    description="Check the 36-column training CSV joint order."
)
parser.add_argument("csv", type=Path)
parser.add_argument(
    "--converted-npz",
    type=Path,
    default=None,
    help="Optional motion.npz generated by csv_to_npz_local.py.",
)
args = parser.parse_args()

pose = np.loadtxt(args.csv, delimiter=",", dtype=np.float64, ndmin=2)
if pose.ndim != 2 or pose.shape[1] != 36:
    raise RuntimeError(
        f"Expected N x 36 CSV, got {pose.shape}"
    )

q_converter = pose[:, 7:]
policy_index = {name: i for i, name in enumerate(POLICY_ORDER)}
q_policy = np.empty_like(q_converter)

for converter_i, joint_name in enumerate(CONVERTER_ORDER):
    q_policy[:, policy_index[joint_name]] = q_converter[:, converter_i]

print("Training CSV mapping: PASS")
print(f"frames={pose.shape[0]}")
print("Input columns 7:36 are in csv_to_npz.py CONVERTER_ORDER.")
print("Reconstructed output order is POLICY_ORDER.")

print("\nConverter column -> output policy index")
for converter_i, joint_name in enumerate(CONVERTER_ORDER):
    print(
        f"{converter_i:02d} {joint_name:32s} "
        f"-> {policy_index[joint_name]:02d}"
    )

if args.converted_npz is not None:
    with np.load(args.converted_npz, allow_pickle=False) as data:
        actual = np.asarray(data["joint_pos"])
    if actual.shape != q_policy.shape:
        raise RuntimeError(
            f"Converted NPZ joint_pos shape {actual.shape} "
            f"does not match CSV {q_policy.shape}"
        )
    error = float(np.max(np.abs(actual - q_policy)))
    print(f"\nNPZ joint_pos max error={error:.3e} rad")
    if error > 2e-5:
        raise RuntimeError(
            "Converted NPZ does not match the expected policy order."
        )
    print("Converted NPZ mapping: PASS")
